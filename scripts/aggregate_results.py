"""
Авто-генерация таблиц для REPORT.md из всех result.json файлов.

Что делает:
  1. Идёт по results/**/result.json
  2. Группирует по RQ → method → dataset
  3. Если несколько сидов на одну ячейку — считает mean ± std
  4. Рендерит REPORT_GENERATED.md с 4 таблицами (одна на RQ)

Зачем: чтобы не заполнять REPORT.md руками после каждого re-run.

Запуск:
  python scripts/aggregate_results.py
  # или
  make aggregate
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev


_RQ_DISPLAY_ORDER = ["RQ1", "RQ2-D1", "RQ2-D2", "RQ3"]


def load_all_results(results_root: Path) -> list[dict]:
    found_results = []
    for result_path in sorted(results_root.glob("**/result.json")):
        try:
            with result_path.open(encoding="utf-8") as file_handle:
                payload = json.load(file_handle)
            payload["_source_path"] = str(result_path)
            found_results.append(payload)
        except (json.JSONDecodeError, OSError) as load_error:
            print(f"  [skip] {result_path}: {load_error}")
    return found_results


def group_by_method_and_dataset(results: list[dict]) -> dict[tuple[str, str, str], list[dict]]:
    grouped = defaultdict(list)
    for entry in results:
        key = (
            entry.get("rq", "unknown"),
            entry.get("method", "unknown"),
            entry.get("dataset", "unknown"),
        )
        grouped[key].append(entry)
    return grouped


def format_metric_value(values: list[float]) -> str:
    if not values:
        return "—"
    if len(values) == 1:
        return f"{values[0]:.4f}"
    return f"{mean(values):.4f} ± {stdev(values):.4f}"


def render_rq_section(rq_name: str, all_results: list[dict]) -> str:
    grouped = group_by_method_and_dataset(all_results)
    rows_for_rq = []

    for (rq_value, method, dataset), entries in sorted(grouped.items()):
        if rq_value != rq_name:
            continue
        metric_keys = set()
        for entry in entries:
            metric_keys.update(entry.get("metrics", {}).keys())

        for metric_key in sorted(metric_keys):
            metric_values = [
                entry["metrics"][metric_key]
                for entry in entries
                if metric_key in entry["metrics"]
            ]
            rows_for_rq.append(
                f"| {method} | {dataset} | {metric_key} | "
                f"{format_metric_value(metric_values)} | {len(entries)} |"
            )

    if not rows_for_rq:
        return f"## {rq_name}\n\n_No results found._\n"

    table_header = (
        f"## {rq_name}\n\n"
        "| Method | Dataset | Metric | Value (mean ± std) | n_seeds |\n"
        "|---|---|---|---|---|\n"
    )
    return table_header + "\n".join(rows_for_rq) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", default="results", type=Path)
    parser.add_argument("--output", default="REPORT_GENERATED.md", type=Path)
    arguments = parser.parse_args()

    if not arguments.results_root.exists():
        print(f"Results root not found: {arguments.results_root}")
        return

    all_results = load_all_results(arguments.results_root)
    print(f"Loaded {len(all_results)} result.json files")

    if not all_results:
        print("No results to aggregate.")
        return

    sections = [render_rq_section(rq_name, all_results) for rq_name in _RQ_DISPLAY_ORDER]

    output_text = (
        "# Auto-generated experiment results\n\n"
        "Generated by `scripts/aggregate_results.py` from `results/**/result.json`.\n"
        "Do not edit manually — regenerate with `make aggregate`.\n\n"
        + "\n".join(sections)
    )

    arguments.output.write_text(output_text, encoding="utf-8")
    print(f"Wrote {arguments.output}")


if __name__ == "__main__":
    main()
